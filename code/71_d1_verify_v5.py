"""D1 verifier — acceptance gate for data/sim_v5 (card t_2ba30073).

Checks (recomputed from disk, never from the generator's in-memory state):
  (a) >=4 classes x >=200 runs with full export set on disk
  (b) label = injected physical parameter, hash-chained to the run:
      canonical hash(scenario.json) == label.json == run_metadata.provenance
      == ground_truth.run, seed match, injected params match scenario content
  (c) manifest.csv complete: one row per run, key fields non-empty, chain ok
  (d) determinism: 3 sampled runs regenerated byte-identical (SHA256 of all
      7 CLI export files + scenario.json + label.json)

Usage: python 71_d1_verify_v5.py [--sample-determinism 3]
Exit 0 = all gates PASS.
"""
import argparse
import concurrent.futures
import csv
import hashlib
import json
import random
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path("/mnt/d/Capstone 1")
SIM_V5 = ROOT / "data/sim_v5"
CLI = Path.home() / ".hermes/cache/scratch/r1-rigsim-venv/bin/rig-telemetry-sim"
REGEN_DIR = Path.home() / ".hermes/cache/scratch/d1_regen_check"
CLI_FILES = ("surface_telemetry.csv", "pipe_tally.csv", "surveys.csv",
             "events.json", "ground_truth.json", "run_metadata.json")


def canonical_hash(data: dict) -> str:
    return hashlib.sha256(
        json.dumps(data, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def check_a() -> tuple[bool, str]:
    counts = {}
    full = 0
    for cls_dir in sorted(p for p in SIM_V5.iterdir() if p.is_dir()):
        runs = [r for r in cls_dir.iterdir() if r.is_dir()]
        ok_runs = [r for r in runs if (r / "surface_telemetry.csv").exists()
                   and (r / "ground_truth.json").exists()]
        counts[cls_dir.name] = (len(runs), len(ok_runs))
        if len(ok_runs) >= 200:
            full += 1
    ok = full >= 4
    lines = [f"  {k}: {v[0]} run dirs, {v[1]} with full export" for k, v in counts.items()]
    return ok, f"(a) classes with >=200 full runs: {full}\n" + "\n".join(lines)


def check_b() -> tuple[bool, str]:
    bad = []
    n = 0
    for cls_dir in sorted(p for p in SIM_V5.iterdir() if p.is_dir()):
        for run_dir in sorted(r for r in cls_dir.iterdir() if r.is_dir()):
            n += 1
            try:
                scen = json.loads((run_dir / "scenario.json").read_text())
                label = json.loads((run_dir / "label.json").read_text())
                meta = json.loads((run_dir / "run_metadata.json").read_text())
                gt = json.loads((run_dir / "ground_truth.json").read_text())
            except Exception as exc:  # noqa: BLE001
                bad.append(f"{run_dir.name}: unreadable ({exc})")
                continue
            ch = canonical_hash(scen)
            if not (ch == label["canonical_scenario_hash"]
                    == meta["provenance"]["canonical_scenario_hash"]
                    == gt["run"]["canonical_scenario_hash"]):
                bad.append(f"{run_dir.name}: hash chain broken")
            if meta["seed"] != label["seed"] or scen["seed"] != label["seed"]:
                bad.append(f"{run_dir.name}: seed mismatch")
            ip = label["injected_parameters"]
            if scen["formation"]["intervals"][0]["ucs_pa"] != ip["formation.ucs_pa"]:
                bad.append(f"{run_dir.name}: ucs label != scenario")
            if scen["bit"]["cutting_efficiency"] != ip["bit.cutting_efficiency"]:
                bad.append(f"{run_dir.name}: cut_eff label != scenario")
            if label["class_label"] != cls_dir.name:
                bad.append(f"{run_dir.name}: class dir/label mismatch")
    ok = not bad
    msg = f"(b) label provenance: {n} runs checked, {len(bad)} violations"
    if bad:
        msg += "\n  " + "\n  ".join(bad[:10])
    return ok, msg


def check_c() -> tuple[bool, str]:
    with open(SIM_V5 / "manifest.csv") as fh:
        rows = list(csv.DictReader(fh))
    # explicit iteration (proven to enumerate all 1200 runs on this drvfs mount)
    on_disk = {run_dir.name
               for cls_dir in SIM_V5.iterdir() if cls_dir.is_dir()
               for run_dir in cls_dir.iterdir() if run_dir.is_dir()
               if (run_dir / "label.json").exists()}
    in_manifest = {r["run_id"] for r in rows}
    missing = on_disk - in_manifest
    phantom = in_manifest - on_disk
    key_cols = ("run_id", "class_label", "seed", "canonical_scenario_hash",
                "csv_sha256", "n_rows", "status", "hash_chain_ok")
    empty = [r["run_id"] for r in rows
             if any(not str(r.get(c, "")).strip() for c in key_cols)]
    chain_bad = [r["run_id"] for r in rows if r.get("hash_chain_ok") != "True"]
    # csv_sha256 spot check: recompute for 20 sampled rows
    rng = random.Random(123)
    sample = rng.sample(rows, min(20, len(rows)))
    sha_bad = []
    for r in sample:
        run_dir = SIM_V5 / r["class_label"] / r["run_id"]
        if sha256_file(run_dir / "surface_telemetry.csv") != r["csv_sha256"]:
            sha_bad.append(r["run_id"])
    ok = not (missing or phantom or empty or chain_bad or sha_bad)
    msg = (f"(c) manifest: {len(rows)} rows vs {len(on_disk)} runs | "
           f"missing={len(missing)} phantom={len(phantom)} empty_key={len(empty)} "
           f"chain_bad={len(chain_bad)} sha_spotcheck_bad={len(sha_bad)}")
    return ok, msg


def regen_one(args: tuple[str, int, int]) -> dict:
    cls, idx, master_seed = args
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        "gen", ROOT / "code/70_d1_generate_v5.py")
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    rng = random.Random(f"{master_seed}:{cls}:{idx}")
    params = gen.sample_params(cls, rng)
    seed = master_seed * 1000 + gen.CLASSES.index(cls) * 250 + idx
    sc = gen.build_scenario(cls, params, seed)
    out = REGEN_DIR / f"{cls}_r{idx:04d}"
    if out.exists():
        shutil.rmtree(out)
    scen_file = out.with_suffix(".json")
    scen_file.write_text(json.dumps(sc, indent=2))
    proc = subprocess.run(
        [str(CLI), "generate", str(scen_file), "--output", str(out), "--no-parquet"],
        capture_output=True, text=True)
    if proc.returncode != 0:
        return {"run": out.name, "ok": False, "why": f"rc={proc.returncode}"}
    orig = SIM_V5 / cls / f"{cls}_r{idx:04d}"
    diffs = []
    for f in CLI_FILES:
        if sha256_file(out / f) != sha256_file(orig / f):
            diffs.append(f)
    return {"run": out.name, "ok": not diffs,
            "why": "byte-identical" if not diffs else f"differs: {diffs}"}


def check_d(master_seed: int, sample_n: int) -> tuple[bool, str]:
    if REGEN_DIR.exists():
        shutil.rmtree(REGEN_DIR)
    REGEN_DIR.mkdir(parents=True)
    rng = random.Random(7)
    picks = []
    cls_dirs = sorted(p.name for p in SIM_V5.iterdir() if p.is_dir())
    per = max(1, sample_n // len(cls_dirs))
    for cls in cls_dirs:
        idxs = sorted(int(p.name.rsplit("_r", 1)[1]) for p in (SIM_V5 / cls).iterdir()
                      if p.is_dir())
        picks += [(cls, i, master_seed) for i in rng.sample(idxs, min(per, len(idxs)))]
    results = []
    with concurrent.futures.ProcessPoolExecutor(len(picks)) as ex:
        for res in ex.map(regen_one, picks):
            results.append(res)
            print(f"    regen {res['run']}: {'PASS' if res['ok'] else 'FAIL'} "
                  f"({res['why']})", flush=True)
    ok = all(r["ok"] for r in results)
    return ok, f"(d) determinism: {sum(r['ok'] for r in results)}/{len(results)} " \
               f"regenerated byte-identical"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sample-determinism", type=int, default=3)
    ap.add_argument("--master-seed", type=int, default=20261010)
    args = ap.parse_args()
    if not SIM_V5.exists():
        print(f"FATAL: {SIM_V5} does not exist")
        return 2
    outcomes = []
    for fn, arg in ((check_a, None), (check_b, None), (check_c, None)):
        ok, msg = fn()
        print(msg, flush=True)
        outcomes.append(ok)
    ok, msg = check_d(args.master_seed, args.sample_determinism)
    print(msg, flush=True)
    outcomes.append(ok)
    verdict = "ALL GATES PASS" if all(outcomes) else "GATE FAILED"
    print(f"\nVERDICT: {verdict} ({sum(outcomes)}/{len(outcomes)})")
    return 0 if all(outcomes) else 1


if __name__ == "__main__":
    sys.exit(main())
